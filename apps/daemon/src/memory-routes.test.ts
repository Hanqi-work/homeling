import { afterEach, expect, test } from "bun:test";
import { mkdtemp, realpath, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { PersonaRegistry } from "./persona-registry.ts";
import { PersonaMemoryStore } from "./persona-memory.ts";
import { handleMemoryRequest } from "./memory-routes.ts";
import { SessionLock } from "./session-lock.ts";
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });
test("memory HTTP view, conditional save, unsupported notice and lock refusal", async () => {
  const root = await realpath(await mkdtemp(join(tmpdir(), "homeling-memory-route-"))); roots.push(root);
  const registry = new PersonaRegistry(join(root, "registry.json"));
  await registry.createPersona({ id: "p", name: "Mira", avatar: { color: "#86efac" }, spaceId: "w", mainPaneId: "pane", systemPrompt: "", createdAt: "2026-10-09", launcherCommand: "claude" });
  const runtime = { registry, memory: new PersonaMemoryStore(join(root, "memory")) };
  const url = "http://localhost/lite/api/persona/p/memory";
  const view = await handleMemoryRequest(new Request(url), runtime);
  const initial = await view!.json();
  expect(initial).toMatchObject({ effective: "next-session", injection: { unsupported: true, strategy: "first-message-prefix" } });
  const body = JSON.stringify({ kind: "facts", content: "Lives in Guangzhou", revision: initial.documents.facts.revision });
  const request = () => new Request(url, { method: "PUT", headers: { "content-type": "application/json" }, body });
  expect((await handleMemoryRequest(request(), runtime))!.status).toBe(423);
  expect((await runtime.memory.read("p")).documents.facts.content).toBe("");
  const lock = new SessionLock(), { token } = lock.unlock("fixture");
  const admission = lock.admission(lock.admit(token, "fixture"));
  expect((await handleMemoryRequest(request(), runtime, admission))!.status).toBe(200);
  expect((await handleMemoryRequest(request(), runtime, admission))!.status).toBe(409);
  lock.lock(token, "fixture");
  expect((await handleMemoryRequest(request(), runtime, admission))!.status).toBe(423);
  expect((await runtime.memory.read("p")).documents.facts.content).toBe("Lives in Guangzhou");
});
